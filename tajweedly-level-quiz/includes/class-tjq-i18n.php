	public static function lang() {
		$l = TJQ_Settings::get( 'lang' );
		if ( 'auto' === $l || ! $l ) {
			$l = substr( determine_locale(), 0, 2 );
		}
		return in_array( $l, array( 'en', 'ar', 'ur', 'fr' ), true ) ? $l : 'en';
	}

	public static function is_rtl( $lang ) {
		return in_array( $lang, array( 'ar', 'ur' ), true );
	}

